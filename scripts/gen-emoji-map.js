// Generates server/src/lib/emojiMap.ts: every standard emoji shortcode name
// (iamcal/emoji-data short_names, which Root uses for reactions) mapped to its
// Unicode text, so messages can show real emoji instead of ":name:". Base
// forms only; skin-tone variations are left out.
//
// Run by hand when emoji-data gains new emoji; the output is committed:
//   node scripts/gen-emoji-map.js

const fs = require("fs");
const path = require("path");

const SOURCE = "https://raw.githubusercontent.com/iamcal/emoji-data/master/emoji.json";
const OUT = path.join(__dirname, "..", "server", "src", "lib", "emojiMap.ts");

(async () => {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
  const emoji = await res.json();
  const map = new Map();
  for (const e of emoji) {
    const text = String.fromCodePoint(...e.unified.split("-").map((hex) => parseInt(hex, 16)));
    for (const name of e.short_names) if (!map.has(name)) map.set(name, text);
  }
  const lines = [...map].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([name, text]) => `${JSON.stringify(name)}:${JSON.stringify(text)},`);
  const body = [
    "// Generated by scripts/gen-emoji-map.js from iamcal/emoji-data. Do not edit.",
    "// Standard emoji shortcode name (without colons) -> Unicode text.",
    "export const EMOJI_MAP: Record<string, string> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${map.size} names to ${path.relative(process.cwd(), OUT)}`);
})().catch((err) => {
  console.error(err);
  process.exit(1);
});
